import {readFile,writeFile} from 'node:fs/promises';
import vm from 'node:vm';
const root=new URL('../',import.meta.url);
const context=vm.createContext({});
for(const file of ['i18n-data.js','engine.js','story-engine.js','styling.js'])vm.runInContext(await readFile(new URL(file,root),'utf8'),context);
const base=context.ScentLocaleData,extra={};
function add(key,values){if(key)extra[key]={en:values[0],zh:values[1],ja:values[2]};}
for(const line of (await readFile(new URL('locales/extra.txt',root),'utf8')).trim().split('\n').filter(line=>line.trim())){const [key,...values]=line.split('|');if(values.length!==3)throw Error('Invalid translation row: '+key);add(key,values);}
const editorial=JSON.parse(await readFile(new URL('locales/editorial.json',root),'utf8'));
for(const s of context.ScentStyle.styles)for(const [field,values] of Object.entries(editorial.styles[s.id]))add(s[field],values);
for(const t of context.StoryScent.themes)['label','title','meaning','pairing'].forEach((field,i)=>add(t[field],editorial.themes[t.id][i]));
const catalog=JSON.parse(await readFile(new URL('data/fragrance-catalog.json',root),'utf8'));
const names=(await readFile(new URL('locales/fragrance-names.txt',root),'utf8')).trim().split('\n');
if(names.length!==72)throw Error('Expected 72 fragrance names');
const languages=['en','zh','ja'];
function t(text,lang){return extra[text]?.[lang]||base[text]?.[lang]||text;}
for(const s of catalog.mainScents){
  const name=names[Number(s.number)-1]+' type';add(s.name,[name,name,name]);
  if(s.notes&&s.noteSource){
    const summaries=languages.map(lang=>{
      const list=key=>(s.notes[key]||[]).slice(0,2).map(x=>t(x,lang)).join(' · ');
      if(s.noteStatus!=='pyramid'){const notes=(s.notes.key||[]).slice(0,3).map(x=>t(x,lang)).join(' · ');return lang==='en'?`Key notes: ${notes}.`:lang==='zh'?`主要香调：${notes}。`:`主なノート：${notes}。`;}
      return lang==='en'?`Opens with ${list('top')}; a heart of ${list('heart')}; a finish of ${list('base')}.`:lang==='zh'?`前调${list('top')}，中调${list('heart')}，后调留下${list('base')}的余韵。`:`${list('top')}で始まり、${list('heart')}のハートから${list('base')}の余韻へ。`;
    });add(s.shortDescription,summaries);
    add(s.description,languages.map(lang=>[...new Set([...(s.accords||[]),...Object.values(s.notes).flat()])].map(x=>t(x,lang)).join(' · ')));
  }
}
const forms={
  '브로치':['brooch','胸针','ブローチ'],'귀고리':['earrings','耳环','イヤリング'],'찻잔':['teacup','茶杯','ティーカップ'],'참 백':['charm bag','挂饰包','チャームバッグ'],
  '팔찌':['bracelet','手链','ブレスレット'],'소품':['accent','摆件','小物'],'목걸이':['necklace','项链','ネックレス'],'오브제':['object','摆件','オブジェ'],
  '헤어핀':['hairpin','发夹','ヘアピン'],'조개 목걸이':['shell necklace','贝壳项链','シェルネックレス'],'꽃 참':['flower charm','花朵挂饰','フラワーチャーム'],
  '꽃다발':['bouquet','花束','ブーケ'],'화병':['vase','花瓶','花瓶'],'코사지':['corsage','胸花','コサージュ'],'테라리움':['terrarium','苔藓微景观','テラリウム'],
  '잎 브로치':['leaf brooch','叶片胸针','リーフブローチ'],'우드 뱅글':['wood bangle','木手镯','ウッドバングル'],'우드 참':['wood charm','木质挂饰','ウッドチャーム'],
  '진주 목걸이':['pearl necklace','珍珠项链','パールネックレス'],'보석 반지':['gem ring','宝石戒指','ジェムリング'],'리본':['ribbon','蝴蝶结','リボン'],'파우치':['pouch','小袋','ポーチ']
};
for(const single of catalog.singleScents){
  const d=context.ScentStyling.descriptor(single);const form=Object.keys(forms).sort((a,b)=>b.length-a.length).find(k=>d.label.endsWith(' '+k));
  if(!form)throw Error('Accessory form missing: '+d.label);
  const prefix=d.label.slice(0,-form.length).trim();
  add(d.label,languages.map((lang,i)=>t(prefix,lang)+(lang==='en'?' ':'')+forms[form][i]));
}
const unknown=[...new Set(catalog.mainScents.flatMap(s=>Object.values(s.notes||{}).flat()))].filter(k=>languages.some(lang=>/[가-힣]/.test(t(k,lang))));
if(unknown.length)throw Error('Untranslated notes: '+unknown.join(', '));
await writeFile(new URL('i18n-catalog.js',root),'// Generated by node locales/build.mjs\nObject.assign(globalThis.ScentLocaleData,'+JSON.stringify(extra)+');\nglobalThis.StoryLocaleKeywords='+JSON.stringify(editorial.keywords)+';\n');
console.log('Compiled 72 scent names, all reference notes, 30 accessories, 8 styles and 18 story themes.');
